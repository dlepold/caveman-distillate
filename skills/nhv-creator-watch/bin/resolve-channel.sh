#!/usr/bin/env bash
# Resolve the creator's channel from CW_SEED_URL and discover where they publish.
# Writes facts to state/resolved.sh so later runs skip resolution.
#
# Method (kept reproducible on purpose — "merk dir wie es ging"):
#   1. yt-dlp --dump-single-json on the seed URL  → channel, channel_id,
#      channel_url, uploader_url, plus description (scanned for outbound links).
#   2. Fallback when yt-dlp is missing: YouTube oEmbed endpoint
#      (https://www.youtube.com/oembed?...) → author_name + author_url.
#   3. Outbound links in the channel "About"/description (http/https) become
#      candidate CW_EXTRA_FEEDS (blog/Substack/X/…).
#
# Note: this needs real network access to YouTube. It runs on TB16, NOT in the
# Claude cloud sandbox (which blocks youtube.com).

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../lib" && pwd)/common.sh"
cw::load_config

write_resolved() {
  local id="$1" handle="$2" url="$3" uploader="$4" links="$5"
  cat > "$CW_RESOLVED_FILE" <<EOF
# Auto-generated by resolve-channel.sh on $(date '+%Y-%m-%d %H:%M:%S'). Edit config.sh instead.
CW_CHANNEL_ID="${id}"
CW_CHANNEL_HANDLE="${handle}"
CW_CHANNEL_URL="${url}"
CW_UPLOADER="${uploader}"
CW_DISCOVERED_LINKS="${links}"
EOF
  cw::log "wrote $CW_RESOLVED_FILE"
}

# Already resolved and not forced? Done.
if [[ -n "${CW_CHANNEL_ID:-}" && "${1:-}" != "--force" ]]; then
  cw::log "channel already set (CW_CHANNEL_ID=$CW_CHANNEL_ID). Use --force to re-resolve."
  exit 0
fi

[[ -n "${CW_SEED_URL:-}" ]] || cw::die "CW_SEED_URL is empty — set it in config.sh."

if cw::have yt-dlp; then
  cw::log "resolving via yt-dlp: $CW_SEED_URL"
  json="$(yt-dlp --no-warnings --dump-single-json "$CW_SEED_URL")" \
    || cw::die "yt-dlp failed on $CW_SEED_URL"

  pick() { printf '%s' "$json" | python3 -c "import sys,json;d=json.load(sys.stdin);print(d.get('$1','') or '')"; }
  cid="$(pick channel_id)"
  curl_url="$(pick channel_url)"
  uploader="$(pick channel)"; [[ -n "$uploader" ]] || uploader="$(pick uploader)"
  handle="$(pick uploader_id)"
  desc="$(pick description)"

  # Outbound links from the video/channel description.
  links="$(printf '%s\n' "$desc" \
    | grep -oE 'https?://[^[:space:]]+' \
    | grep -viE 'youtube\.com|youtu\.be' \
    | sort -u | tr '\n' ' ' | sed 's/ *$//' || true)"

  write_resolved "$cid" "$handle" "$curl_url" "$uploader" "$links"
  cw::log "channel: ${uploader:-?}  id=${cid:-?}  handle=${handle:-?}"
  [[ -n "$links" ]] && cw::log "discovered links: $links" || cw::log "no outbound links found in description."
  exit 0
fi

# --- Fallback: oEmbed (gives author name + channel URL, no channel_id) -------
cw::have curl || cw::die "neither yt-dlp nor curl available — cannot resolve."
cw::log "yt-dlp missing — falling back to oEmbed (limited: no channel_id)."
oembed="$(curl -fsS "https://www.youtube.com/oembed?format=json&url=$(
  printf '%s' "$CW_SEED_URL" | sed 's/:/%3A/g; s|/|%2F|g')")" \
  || cw::die "oEmbed request failed."
author="$(printf '%s' "$oembed" | python3 -c 'import sys,json;print(json.load(sys.stdin).get("author_name",""))')"
aurl="$(printf '%s' "$oembed" | python3 -c 'import sys,json;print(json.load(sys.stdin).get("author_url",""))')"
write_resolved "" "" "$aurl" "$author" ""
cw::log "resolved (oEmbed): $author  $aurl"
cw::log "NOTE: install yt-dlp to get channel_id (needed for the RSS feed) and link discovery."
